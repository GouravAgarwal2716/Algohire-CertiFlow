import { describe, it, expect, beforeAll } from 'vitest';
import request from 'supertest';
import { BatchStatus, WhatsAppStatus } from '@prisma/client';
import { createApp } from '../src/app';
import { prisma } from '../src/config/db';
import { setupTestEnvironment, getAuthToken, createTestBatch } from './test-helpers';
import { config } from '../config/env';

const app = createApp();

describe('Moment 3: Exactly-Once Certificate Issuance & Resilient WhatsApp Delivery', () => {
  beforeAll(async () => {
    await setupTestEnvironment();
  });

  it('approves a batch and enqueues jobs that generate exactly one certificate per candidate', async () => {
    const farahToken = getAuthToken('farah');

    // Create a batch with candidates in PENDING_STATE
    const batch = await createTestBatch({
      title: 'Issuance Validation Batch',
      candidateCount: 5,
    });

    // Insert 5 candidates
    const candidates = await prisma.candidate.createMany({
      data: [
        { batchId: batch.id, fullName: 'Student One', phone: '9871110001', rollNumber: 'ISS-01', score: 85 },
        { batchId: batch.id, fullName: 'Student Two', phone: '9871110002', rollNumber: 'ISS-02', score: 90 },
        { batchId: batch.id, fullName: 'Student Three', phone: '9871110003', rollNumber: 'ISS-03', score: 88 },
        { batchId: batch.id, fullName: 'Student Four', phone: '9871110004', rollNumber: 'ISS-04', score: 76 },
        { batchId: batch.id, fullName: 'Student Five', phone: '9871110005', rollNumber: 'ISS-05', score: 92 },
      ],
    });

    await prisma.batch.update({
      where: { id: batch.id },
      data: { status: BatchStatus.PENDING_STATE, candidateCount: 5 },
    });

    // Farah gives final approval -> transitions to ISSUING immediately
    const res = await request(app)
      .post(`/api/batches/${batch.id}/approve`)
      .set('Authorization', `Bearer ${farahToken}`)
      .send({ reason: 'Final state clearance granted' });

    expect(res.status).toBe(200);

    const check = await prisma.batch.findUnique({ where: { id: batch.id } });
    expect(check?.status).toBe(BatchStatus.ISSUING);

    // Verify that candidates cannot have duplicate certificates due to @@unique constraint
    const allCands = await prisma.candidate.findMany({ where: { batchId: batch.id } });
    for (const cand of allCands) {
      // Find existing certificate generated by background worker or insert test record
      let cert1 = await prisma.certificate.findUnique({ where: { candidateId: cand.id } });
      if (!cert1) {
        try {
          cert1 = await prisma.certificate.create({
            data: {
              certificateNumber: `PSM-TEST-${cand.rollNumber}-${Date.now()}`,
              verificationCode: `code-${cand.rollNumber}`,
              batchId: batch.id,
              candidateId: cand.id,
              whatsappStatus: WhatsAppStatus.SENT,
            },
          });
        } catch {
          cert1 = await prisma.certificate.findUnique({ where: { candidateId: cand.id } });
        }
      }
      expect(cert1).toBeDefined();

      // Attempting to insert a duplicate certificate for the same candidate throws unique violation
      await expect(
        prisma.certificate.create({
          data: {
            certificateNumber: `PSM-DUP-${cand.rollNumber}-${Date.now()}`,
            verificationCode: `dupcode-${cand.rollNumber}`,
            batchId: batch.id,
            candidateId: cand.id,
          },
        })
      ).rejects.toThrow();
    }

    // Verify all 5 candidates have exactly 1 certificate
    const certCount = await prisma.certificate.count({ where: { batchId: batch.id } });
    expect(certCount).toBe(5);
  });
});
